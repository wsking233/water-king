import { writeFileSync, mkdirSync } from "node:fs";
import { profileModel } from "../src/cloud/models.ts";

// Run during development/deployment, never in an untrusted browser client.
const { table, columns } = profileModel;
const sql = `-- Generated by npm run schema:generate from src/cloud/models.ts.
-- Apply once through an authorized Supabase schema deployment tool.
create table public.${table} (
${Object.entries(columns).map(([name, sql]) => `  ${name} ${sql}`).join(",\n")}
);
alter table public.${table} enable row level security;
revoke all on table public.${table} from anon, authenticated;
grant select on table public.${table} to authenticated;
grant insert (user_id, nickname) on table public.${table} to authenticated;
grant update (nickname) on table public.${table} to authenticated;
create policy profiles_select_own on public.${table}
  for select to authenticated using ((select auth.uid()) = user_id);
create policy profiles_insert_own on public.${table}
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy profiles_update_own on public.${table}
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
`;
mkdirSync(new URL("../supabase/", import.meta.url), { recursive: true });
writeFileSync(new URL("../supabase/schema.sql", import.meta.url), sql);
