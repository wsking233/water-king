import { readFileSync, writeFileSync } from "node:fs";

// Keep existing RPC implementations intact, replacing only their auth entry.
// The generated upgrade is deployed once after transactional integration tests.
const source = readFileSync(new URL("../supabase/sync-schema.sql",import.meta.url),"utf8");
const start = source.indexOf("create function waterking_private.apply_mutation(");
const end = source.indexOf("revoke all on function waterking_private.apply_mutation(",start);
let functions = source.slice(start,end).replaceAll("create function ","create or replace function ");
const auth = /  if uid is null or not exists \(select 1 from auth\.users where id = uid\) then\n    raise exception 'Authentication required' using errcode = '42501';\n  end if;/g;
if ([...functions.matchAll(auth)].length !== 2) throw Error("Sync auth entry changed; review lifecycle upgrade");
functions=functions.replace(auth,"  uid := waterking_private.require_active_user(true);");
writeFileSync(new URL("../supabase/lifecycle-upgrade.sql",import.meta.url),
  "-- Generated by npm run lifecycle:generate. Apply after sync-schema.sql.\n"
  +readFileSync(new URL("../supabase/lifecycle-schema.sql",import.meta.url),"utf8")+"\n"+functions+"\nnotify pgrst, 'reload schema';\n");
